/**
 * Match a category by name, slug, or ID
 */
export function getCategoryTaxonomy(categoryInput) {
  if (!categoryInput) return null;
  const inputStr = normalizeArabic(String(categoryInput)).toLowerCase();

  for (const item of SPECIALIZED_CATEGORIES_TAXONOMY) {
    const catNorm = normalizeArabic(item.category).toLowerCase();
    if (
      catNorm === inputStr ||
      catNorm.includes(inputStr) ||
      inputStr.includes(catNorm) ||
      item.categoryEn.toLowerCase() === inputStr ||
      item.id === Number(categoryInput)
    ) {
      return item;
    }
  }
  return null;
}

